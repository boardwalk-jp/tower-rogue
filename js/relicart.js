  // ---------- 1ドット単位で描く道具 ----------
  function R(c, col, x, y, w, h) { c.fillStyle = col; c.fillRect(Math.round(x), Math.round(y), w || 1, h || 1); }
  // 楕円（まん中 cx,cy・横の半径 rx・縦の半径 ry）をドットで塗る
  function ell(c, col, cx, cy, rx, ry) {
    for (var y = Math.floor(cy - ry); y <= Math.ceil(cy + ry); y++)
      for (var x = Math.floor(cx - rx); x <= Math.ceil(cx + rx); x++) {
        var a = (x + 0.5 - cx) / rx, b = (y + 0.5 - cy) / ry;
        if (a * a + b * b <= 1) R(c, col, x, y);
      }
  }
  // 多角形（点の並び [[x,y],...]）をドットで塗る。ドットの中心が中に入っていれば塗る
  function poly(c, col, pts) {
    var minY = Infinity, maxY = -Infinity, i;
    for (i = 0; i < pts.length; i++) { minY = Math.min(minY, pts[i][1]); maxY = Math.max(maxY, pts[i][1]); }
    for (var y = Math.floor(minY); y <= Math.ceil(maxY); y++) {
      var py = y + 0.5, xs = [];
      for (i = 0; i < pts.length; i++) {
        var a = pts[i], b = pts[(i + 1) % pts.length];
        if ((a[1] <= py && b[1] > py) || (b[1] <= py && a[1] > py)) xs.push(a[0] + (py - a[1]) / (b[1] - a[1]) * (b[0] - a[0]));
      }
      xs.sort(function (p, q) { return p - q; });
      for (i = 0; i + 1 < xs.length; i += 2)
        for (var x = Math.ceil(xs[i] - 0.5); x <= Math.floor(xs[i + 1] - 0.5); x++) R(c, col, x, y);
    }
  }
  // 線（1ドットの太さ）
  function line(c, col, x0, y0, x1, y1) {
    x0 = Math.round(x0); y0 = Math.round(y0); x1 = Math.round(x1); y1 = Math.round(y1);
    var dx = Math.abs(x1 - x0), dy = -Math.abs(y1 - y0), sx = x0 < x1 ? 1 : -1, sy = y0 < y1 ? 1 : -1, e = dx + dy;
    for (;;) { R(c, col, x0, y0); if (x0 === x1 && y0 === y1) break; var e2 = 2 * e; if (e2 >= dy) { e += dy; x0 += sx; } if (e2 <= dx) { e += dx; y0 += sy; } }
  }
  // 足もとの影（右に少しずらす＝光が左上から来ているので）
  function shadow(c, cx, cy, rx, a) { ell(c, 'rgba(0,0,0,' + (a || 0.35) + ')', cx + 1, cy, rx, Math.max(1.2, rx * 0.28)); }
  // 丸い物の明るさ：左ほど明るく、右ほど暗い（k は -1〜1。まん中が0）
  function shade(k, P) { return k < -0.45 ? P.hi : k < 0.15 ? P.f : k < 0.6 ? P.s : P.d; }

  var T = { R: R, ell: ell, poly: poly, line: line, shadow: shadow, shade: shade };

